#include <iostream>
using namespace std;

int main () {
    int nilai;
    cout << "Masukkan nilai [0-100] :";
    cin >> nilai;

    if (nilai >= 80)
    {
        cout << "A";
    }else if (nilai >= 70)
    {
        cout << "B";
    }else if (nilai >= 60)
    {
        cout << "C";
    }else if (nilai >= 50)
    {
        cout << "D";
    }else

    {
        cout << "E";
    }
    
    
    
    
}
